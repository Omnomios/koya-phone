import assert from 'node:assert/strict';
import { cleanCredential, credentialAnswer, credentialMode, validPin } from '../apps/credential-model.js';
import { lockController } from '../apps/lock-controller.js';
import { swipeGesture } from '../apps/swipe.js';
for (const height of [540, 1140]) {
  const gesture = swipeGesture(height), start = { x: 150, y: height - 80 };
  assert.equal(gesture.up({ x: 150, y: 100 }), false, 'A release without a press revealed authentication');
  for (const end of [start, { x: 150, y: start.y - 20 }, { x: 150, y: start.y + 50 }, { x: 350, y: start.y - 150 }]) {
    gesture.down(start); assert.equal(gesture.up(end), false, 'Accidental input revealed authentication');
  }
  gesture.down(start); gesture.cancel();
  assert.equal(gesture.up({ x: 150, y: start.y - 180 }), false, 'A cancelled swipe revealed authentication');
  gesture.down(start);
  assert.equal(gesture.up({ x: 160, y: start.y - 180 }), true, 'A deliberate upward swipe did not reveal authentication');
}
const profile = { UserName: 'phone', AuthenticationMode: 'pin', AuthenticationSalt: 'a'.repeat(64), PendingAuthenticationMode: 'pin', PendingAuthenticationSalt: 'b'.repeat(64) };
assert.equal(credentialMode(profile, 'phone'), 'pin');
assert.equal(credentialMode(profile, 'root'), 'password');
assert.equal(credentialMode(profile, 'phone', true), 'password');
assert(!validPin('123')); assert(validPin('1234')); assert(validPin('12345')); assert(validPin('123456789012'));
assert(!validPin('1234567890123')); assert(!validPin('1234x'));
const longPassword = 'long password 🔑 '.repeat(100);
assert.equal(cleanCredential(longPassword), longPassword, 'A long password was truncated');
assert.equal(await credentialAnswer('x', 'password', profile, () => { throw Error('PIN derivation called for a password'); }), 'x');
assert.equal(await credentialAnswer(longPassword, 'password', profile, () => { throw Error('PIN derivation called for a password'); }), longPassword);
assert.equal(await credentialAnswer('secret', 'password', profile, () => { throw Error('PIN derivation called for a password'); }), 'secret');
const salt = async (_, salt) => salt;
assert.equal(await credentialAnswer('1234', 'pin', profile, salt), profile.AuthenticationSalt);
assert.equal(await credentialAnswer('1234', 'pin-pending', profile, salt), profile.PendingAuthenticationSalt);
await assert.rejects(credentialAnswer('123', 'pin', profile, salt));
const locked = { Active: true, ScreenState: 'locked', SecureLocked: true, UserName: 'phone', LockGeneration: 1 };
let authenticated, unlocks = [], now = 0, pending;
const controller = lockController({ now: () => now, authenticate: () => new Promise(resolve => { authenticated = resolve; }), unlock: async generation => unlocks.push(generation) });
controller.update(locked); pending = controller.submit('secret');
assert.equal(await controller.submit('duplicate'), false);
controller.update({ ...locked, ScreenState: 'off' }); authenticated({ ok: true });
assert.equal(await pending, false); assert.deepEqual(unlocks, []);
controller.update(locked); pending = controller.submit('secret');
controller.update({ ...locked, LockGeneration: 2 }); authenticated({ ok: true });
assert.equal(await pending, false); assert.deepEqual(unlocks, []);
controller.update(locked); pending = controller.submit('secret'); authenticated({ ok: false });
assert.equal(await pending, false); assert.deepEqual(unlocks, []);
assert.equal(await controller.submit('secret'), false); now = 1001;
pending = controller.submit('secret'); authenticated({ ok: true });
assert.equal(await pending, true); assert.deepEqual(unlocks, [1]);
controller.update({ ...locked, SecureLocked: false }); assert.equal(await controller.submit('secret'), false);
